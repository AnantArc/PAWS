-- ---------- A. Alert kind mapping (firmware → dashboard) ------
create or replace function public.firmware_alert_map_kind()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if new.kind is null or new.kind = 'system' then
    new.kind := coalesce(new.alert_type, 'system');
  end if;
  return new;
end;
$$;

drop trigger if exists firmware_alert_map_kind on public.alerts;
create trigger firmware_alert_map_kind
  before insert on public.alerts
  for each row execute function public.firmware_alert_map_kind();

-- ---------- B. Telemetry enrichment & mission sync trigger ----
-- Triggered on every upload from ESP32. Keeps mission_state synced.
create or replace function public.rewrite_device_telemetry()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_robot    text := coalesce(new.robot_id, new.device_id, 'paws-01');
  v_mission  text;
  v_ts       bigint;
  v_now_ms   bigint := (extract(epoch from clock_timestamp()) * 1000)::bigint;
  v_sensors  jsonb := '{}'::jsonb;
begin
  -- Rows that already carry a full payload (e.g. seed writes) skip enrichment
  if tg_op = 'INSERT' and new.payload is not null and (new.payload ? 'deviceId') then
    return new;
  end if;

  begin
    v_ts := (extract(epoch from (new.recorded_at::timestamptz)) * 1000)::bigint;
  exception when others then
    v_ts := v_now_ms;
  end;
  if new.ts is not null then
    v_ts := new.ts;
  end if;

  -- 1. Ensure Robot exists
  insert into public.robots (id, name, last_seen_at)
  values (v_robot, 'PAWS ' || upper(v_robot), now())
  on conflict (id) do update set last_seen_at = now();

  -- 2. Find or create active running mission for this robot
  select id into v_mission from public.missions
  where status = 'running' and (robot_id = v_robot or robot_id is null)
  order by started_at desc limit 1;

  if v_mission is null then
    v_mission := 'mis_' || replace(gen_random_uuid()::text, '-', '');
    insert into public.missions (id, name, status, started_at, origin, robot_id)
    values (v_mission, 'Field Mission — ' || v_robot, 'running', now(),
            jsonb_build_object('xM', 0, 'yM', 0, 'setAt', v_now_ms), v_robot);
  end if;

  -- 3. Construct Sensor Map (used by frontend dashboard)
  -- Sound
  if new.sound_level is not null or new.mic_raw is not null or new.mic_db is not null then
    v_sensors := v_sensors || jsonb_build_object('sound', jsonb_strip_nulls(jsonb_build_object(
      'amp', round(least(1.0::numeric, greatest(0.0::numeric, coalesce(new.sound_level, new.mic_raw::numeric) / 4095.0)), 4),
      'db', round(coalesce(new.sound_db, new.mic_db::numeric, new.mic_raw::numeric * 40.0 / 4095.0 + 30.0), 1),
      'band', new.sound_band,
      'peakDb', round(coalesce(new.mic_peak_db, new.mic_db::numeric), 1),
      'heardAt', v_ts)));
  end if;

  -- Gas / Smoke
  if new.gas_level is not null or new.mq2_raw is not null or new.lpg_ppm is not null then
    v_sensors := v_sensors || jsonb_build_object('gas', jsonb_strip_nulls(jsonb_build_object(
      'adc', least(4095, greatest(0, round(coalesce(new.gas_level, new.mq2_raw::numeric))))::int,
      'ppm', round(coalesce(new.lpg_ppm, 0), 1),
      'smoke', round(coalesce(new.smoke_ppm, 0), 1),
      'aqiBand', new.aqi_band,
      'warming', (coalesce(new.lpg_ppm, 0) = -1.0),
      'heardAt', v_ts)));
  end if;

  -- Ultrasonic Distance
  if new.ultra_front_cm is not null or new.distance_cm is not null or new.ultrasonic_cm is not null then
    v_sensors := v_sensors || jsonb_build_object('distance', jsonb_strip_nulls(jsonb_build_object(
      'cm', round(coalesce(
        nullif(new.ultra_front_cm, -1),
        nullif(new.distance_cm, -1),
        nullif(new.ultrasonic_cm::numeric, -1)
      ), 1),
      'cmLeft', round(nullif(new.ultra_left_cm, -1), 1),
      'cmRight', round(nullif(new.ultra_right_cm, -1), 1),
      'state', coalesce(new.ultra_state,
        case
          when coalesce(new.ultrasonic_cm, -1) < 0 then 'NO ECHO'
          when coalesce(new.ultrasonic_cm, -1) < 20 then 'STOP'
          when coalesce(new.ultrasonic_cm, -1) < 60 then 'NEAR'
          else 'CLEAR'
        end
      ),
      'heardAt', v_ts)));
  end if;

  -- Laser ToF (VL53L0X)
  if new.laser_distance_mm is not null or new.laser_state is not null then
    v_sensors := v_sensors || jsonb_build_object('laser', jsonb_strip_nulls(jsonb_build_object(
      'mm', round(nullif(new.laser_distance_mm::numeric, -1), 0),
      'state', coalesce(new.laser_state,
        case when new.laser_distance_mm > 0 then 'IN RANGE' else 'NO TARGET' end
      ),
      'match', new.laser_match,
      'heardAt', v_ts)));
  end if;

  -- IMU Tilt & Attitude
  if new.imu_pitch_deg is not null or new.tilt_angle is not null then
    v_sensors := v_sensors || jsonb_build_object('imu', jsonb_strip_nulls(jsonb_build_object(
      'pitchDeg', round(new.imu_pitch_deg, 1),
      'rollDeg', round(new.imu_roll_deg, 1),
      'tiltDeg', round(new.tilt_angle, 1),
      'attitude', new.imu_attitude,
      'headingDeg', new.robot_heading_deg,
      'heardAt', v_ts)));
  end if;

  -- Thermal (MLX90614)
  if new.object_temp_c is not null and new.object_temp_c > -200 then
    v_sensors := v_sensors || jsonb_build_object('thermal', jsonb_strip_nulls(jsonb_build_object(
      'objectC', round(new.object_temp_c::numeric, 1),
      'ambientC', round(coalesce(new.ambient_temp_c::numeric, 0), 1),
      'deltaC', round(coalesce(new.thermal_delta_c, (new.object_temp_c - coalesce(new.ambient_temp_c, 0))::numeric), 1),
      'zone', coalesce(new.thermal_zone,
        case
          when new.object_temp_c > 55 then 'FIRE RISK'
          when new.object_temp_c > 37 then 'HUMAN HEAT'
          else 'NORMAL'
        end
      ),
      'heardAt', v_ts)));
  end if;

  -- Climate (DHT11)
  if (new.humidity_pct is not null and new.humidity_pct > -900) or
     (new.temperature_c is not null and new.temperature_c > -900) then
    v_sensors := v_sensors || jsonb_build_object('climate', jsonb_strip_nulls(jsonb_build_object(
      'tempC', round(new.temperature_c::numeric, 1),
      'humidityPct', round(new.humidity_pct::numeric, 1),
      'band', coalesce(new.humidity_band,
        case
          when new.humidity_pct < 30 then 'DRY'
          when new.humidity_pct < 60 then 'COMFORT'
          when new.humidity_pct < 80 then 'DAMP'
          else 'HUMID'
        end
      ),
      'heardAt', v_ts)));
  end if;

  -- ESP32-CAM Light status
  if new.cam_light_on is not null then
    v_sensors := v_sensors || jsonb_build_object('camera_light', jsonb_build_object('on', new.cam_light_on));
  end if;

  -- Odometry
  if new.robot_x_cm is not null then
    v_sensors := v_sensors || jsonb_build_object('odom', jsonb_strip_nulls(jsonb_build_object(
      'xCm', new.robot_x_cm,
      'yCm', new.robot_y_cm,
      'headingDeg', new.robot_heading_deg,
      'heardAt', v_ts)));
  end if;

  -- 4. Fill row metadata
  new.mission_id := v_mission;
  new.device_id  := v_robot;
  new.robot_id   := v_robot;
  new.ts         := v_ts;
  new.payload    := jsonb_build_object(
      'deviceId', v_robot,
      'ts', v_ts,
      'seq', (v_ts % 1000000000)::int
    ) || v_sensors;

  -- 5. Upsert live state into mission_state
  insert into public.mission_state (mission_id, sensors, updated_at)
  values (v_mission, jsonb_strip_nulls(v_sensors), now())
  on conflict (mission_id) do update
    set sensors    = mission_state.sensors || excluded.sensors,
        updated_at = excluded.updated_at;

  return new;
end;
$$;

