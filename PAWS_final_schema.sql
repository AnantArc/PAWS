-- ===================== 0. EXTENSIONS ========================
create extension if not exists "pgcrypto";

-- ===================== 1. ROBOTS ============================
create table if not exists public.robots (
  id           text primary key,
  name         text not null default '',
  last_seen_at timestamptz default now(),
  created_at   timestamptz default now()
);

-- ===================== 2. MISSIONS ==========================
create table if not exists public.missions (
  id          text primary key,
  name        text not null default 'Field Mission — paws-01',
  status      text not null default 'running',       -- running | paused | ended | idle
  started_at  timestamptz not null default now(),
  ended_at    timestamptz,
  origin      jsonb default '{"xM":0,"yM":0,"setAt":0}'::jsonb,
  robot_id    text references public.robots(id) on delete set null,
  created_at  timestamptz default now()
);

-- ===================== 3. MISSION_STATE =====================
-- Single row per mission, updated in-place by the trigger on
-- every telemetry upload. Merges all sensor readings into JSONB.
create table if not exists public.mission_state (
  mission_id  text primary key references public.missions(id) on delete cascade,
  sensors     jsonb not null default '{}'::jsonb,
  updated_at  timestamptz not null default now()
);

-- ===================== 4. TELEMETRY =========================
-- The ESP32 upserts a SINGLE live row (id=1) every 2 seconds.
-- GENERATED BY DEFAULT so the firmware can supply "id":1 explicitly.
create table if not exists public.telemetry (
  id                  bigint generated by default as identity primary key,

  -- Base columns (managed by trigger & dashboard)
  mission_id          text,
  device_id           text default 'paws-01',
  robot_id            text default 'paws-01',
  ts                  bigint default (extract(epoch from clock_timestamp()) * 1000)::bigint,
  payload             jsonb,
  recorded_at         timestamptz default now(),

  -- ---- Exact fields sent by PAWSv1.2_CODEv4.3.ino ----
  temperature_c       real,
  humidity_pct        real,
  laser_distance_mm   real,
  ultrasonic_cm       real,
  object_temp_c       real,
  ambient_temp_c      real,
  mq2_raw             integer,
  lpg_ppm             numeric,
  smoke_ppm           numeric,
  mic_raw             integer,
  mic_db              real,
  gait_state          integer,           -- 0=STOP 1=FWD 2=BWD 3=TURN_L 4=TURN_R
  hang_mode           boolean,
  battery_voltage     real,
  battery_pct         integer,           -- 0-100
  est_runtime_min     integer,
  cam_light_on        boolean default false, -- v4.3 ESP32-CAM light state
  error_text          text,

  -- ---- Extended telemetry columns (used by trigger & console) ----
  sound_level         numeric,
  sound_db            numeric,
  sound_band          text,
  mic_peak_db         numeric,

  gas_level           numeric,
  aqi_band            text,

  ultra_front_cm      numeric,
  ultra_left_cm       numeric,
  ultra_right_cm      numeric,
  ultra_state         text,

  laser_state         text,
  laser_match         text,

  imu_pitch_deg       numeric,
  imu_roll_deg        numeric,
  imu_attitude        text,

  thermal_delta_c     numeric,
  thermal_zone        text,

  humidity_band       text,

  distance_cm         numeric,
  tilt_angle          numeric,

  pir_state           text,
  pir_events_total    bigint,
  pir_rate_per_min    integer,
  pir_last_trigger_s  bigint,

  robot_x_cm          bigint,
  robot_y_cm          bigint,
  robot_heading_deg   integer,

  created_at          timestamptz default now()
);

-- ===================== 5. DETECTIONS ========================
-- ESP32-CAM YOLO detector (detect_human.py) appends rows here.
-- Payload sent: { label: "person"|"none", confidence: 0.xx, ts: "ISO-8601" }
create table if not exists public.detections (
  id          text primary key default gen_random_uuid()::text,
  mission_id  text,
  device_id   text default 'paws-cam',
  label       text not null default 'none',          -- person | none
  confidence  numeric not null default 0,             -- 0..1
  ts          timestamptz not null default now(),     -- accepts ISO-8601 string from Python
  bbox        jsonb default '{}'::jsonb,
  position    jsonb,
  source      text default 'vision',
  created_at  timestamptz default now()
);

-- ===================== 6. EVENTS ============================
create table if not exists public.events (
  id          text primary key default 'evt_' || replace(gen_random_uuid()::text, '-', ''),
  mission_id  text,
  ts          bigint default (extract(epoch from clock_timestamp()) * 1000)::bigint,
  kind        text not null default 'system',         -- detection | sound_event | alert | command | system | mission | link
  level       text not null default 'info',           -- info | success | warn | critical
  text        text not null default '',
  snapshot    jsonb default '{}'::jsonb,
  ref_id      text,
  created_at  timestamptz default now()
);

-- ===================== 7. ALERTS ============================
-- ESP32 firmware appends alerts; frontend reads and acknowledges them.
-- Payload sent: { alert_type, severity, title, message, robot_id, gait_state, error_text }
create table if not exists public.alerts (
  id          text primary key default 'alrt_' || replace(gen_random_uuid()::text, '-', ''),
  mission_id  text,
  ts          bigint default (extract(epoch from clock_timestamp()) * 1000)::bigint,
  kind        text not null default 'system',         -- sound_event | gas_high | fire_risk | link_lost | obstacle | command | person_detected | CAM_LIGHT_ON
  severity    text not null default 'info',           -- info | warn | critical | high
  message     text not null default '',
  acked_by    text,
  acked_at    timestamptz,

  -- Firmware fields sent by sendInstantAlert()
  alert_type  text,                                   -- BATTERY_LOW | SYSTEM_ERROR | WIFI_DISCONNECTED | CAM_LIGHT_ON
  title       text,
  robot_id    text default 'PAWS_V1',
  gait_state  integer,
  error_text  text,
  created_at  timestamptz default now()
);

-- ===================== 8. COMMANDS ==========================
create table if not exists public.commands (
  id          text primary key default 'cmd_' || replace(gen_random_uuid()::text, '-', ''),
  mission_id  text,
  type        text not null default 'estop',          -- estop | resume | re_anchor | set_mode | deploy_payload
  params      jsonb default '{}'::jsonb,
  issued_by   text default 'operator',
  issued_at   bigint default (extract(epoch from clock_timestamp()) * 1000)::bigint,
  current     text default 'queued',                  -- queued | delivered | acknowledged | done | failed
  stages      jsonb default '[]'::jsonb,
  created_at  timestamptz default now()
);

-- ===================== 9. FUSION_WEIGHTS ====================
create table if not exists public.fusion_weights (
  id          integer primary key default 1,
  vision      numeric not null default 0.35,
  sound       numeric not null default 0.35,
  thermal     numeric not null default 0.30,
  version     text default '2.1',
  updated_at  timestamptz default now()
);

-- ===================== 10. TRAIL_POINTS =====================
create table if not exists public.trail_points (
  id          bigint generated always as identity primary key,
  mission_id  text,
  ts          bigint,
  x           numeric,                                -- metres
  y           numeric,                                -- metres
  score       numeric,                                -- survivor score 0..1
  hazard      numeric,                                -- hazard score 0..1
  gas_ppm     numeric,
  created_at  timestamptz default now()
