-- ============================================================
-- PAWS — FIRMWARE UPDATE FOR EXISTING `telemetry` + `alerts` TABLES
-- Targets the REAL tables in this project (no paws_ prefix).
-- Aligns them with PAWSv1.2_CODEv3.5.ino, which does direct
-- PostgREST calls with the ANON key:
--   POST {SUPABASE_URL}/rest/v1/telemetry   every 2 s
--        UPSERT of the SINGLE live row id = 1
--        (Prefer: resolution=merge-duplicates, return=minimal)
--   POST {SUPABASE_URL}/rest/v1/alerts      on events
--        APPEND-ONLY inserts (one row per alert)
--
-- 100% ADDITIVE — safe to re-run, never drops columns/tables,
-- never modifies or deletes existing rows. Touches ONLY
-- public.telemetry and public.alerts (ESP32-CAM table, clear/logs
-- tables, missions, events, etc. are NOT touched).
--
-- Paste the WHOLE file into Supabase -> SQL Editor -> Run.
-- ============================================================

-- ------------------------------------------------------------------
-- 1. TELEMETRY — single-row LIVE STATE (id = 1), upserted by firmware
--    (existing columns id / mission_id / device_id / ts / payload
--     are kept; only their defaults/identity mode are adjusted)
-- ------------------------------------------------------------------

-- 1a. Allow the firmware to supply an explicit id (required for the
--     id=1 upsert). GENERATED ALWAYS rejects explicit values over
--     REST; BY DEFAULT accepts them and still auto-assigns otherwise.
--     Guarded: if id is not an ALWAYS-identity column, this is a no-op.
do $$
begin
  alter table public.telemetry alter column id set generated by default;
exception when others then
  raise notice 'telemetry.id: not an ALWAYS identity column, left as-is: %', sqlerrm;
end $$;

-- 1b. Add the firmware's flat sensor columns:
alter table public.telemetry add column if not exists temperature_c     real;
alter table public.telemetry add column if not exists humidity_pct      real;
alter table public.telemetry add column if not exists laser_distance_mm real;
alter table public.telemetry add column if not exists ultrasonic_cm     real;
alter table public.telemetry add column if not exists object_temp_c     real;
alter table public.telemetry add column if not exists ambient_temp_c    real;
alter table public.telemetry add column if not exists mq2_raw           integer;
alter table public.telemetry add column if not exists mic_raw           integer;
alter table public.telemetry add column if not exists gait_state        integer;  -- 0=STOP 1=FWD 2=BWD 3=TURN_L 4=TURN_R
alter table public.telemetry add column if not exists hang_mode         boolean;
alter table public.telemetry add column if not exists battery_voltage   real;
alter table public.telemetry add column if not exists battery_pct       integer;  -- 0-100
alter table public.telemetry add column if not exists est_runtime_min   integer;
alter table public.telemetry add column if not exists error_text        text;     -- "NONE" or "DHT_FAIL; LIDAR_FAIL; ..."

-- 1c. Firmware does not send device_id / ts / payload → defaults so the
--     existing NOT NULL columns still pass on insert AND update:
alter table public.telemetry alter column device_id set default 'paws-01';
alter table public.telemetry alter column ts set default (extract(epoch from clock_timestamp()) * 1000)::bigint;

-- 1d. Pack the flat firmware fields into the existing `payload` jsonb
--     column on EVERY insert or update of the live row (payload stays
--     NOT NULL; the BEFORE trigger runs before the constraint check):
create or replace function public.firmware_telemetry_pack_payload()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if new.payload is null then
    new.payload := jsonb_build_object(
      'temperature_c',     new.temperature_c,
      'humidity_pct',      new.humidity_pct,
      'laser_distance_mm', new.laser_distance_mm,
      'ultrasonic_cm',     new.ultrasonic_cm,
      'object_temp_c',     new.object_temp_c,
      'ambient_temp_c',    new.ambient_temp_c,
      'mq2_raw',           new.mq2_raw,
      'mic_raw',           new.mic_raw,
      'gait_state',        new.gait_state,
      'hang_mode',         new.hang_mode,
      'battery_voltage',   new.battery_voltage,
      'battery_pct',       new.battery_pct,
      'est_runtime_min',   new.est_runtime_min,
      'error_text',        new.error_text
    );
  end if;
  return new;
end;
$$;

drop trigger if exists firmware_telemetry_pack_payload on public.telemetry;
create trigger firmware_telemetry_pack_payload
  before insert or update on public.telemetry
  for each row execute function public.firmware_telemetry_pack_payload();

-- 1e. Seed the single live row (id = 1). Idempotent; the firmware's
--     upsert will UPDATE this row from now on:
insert into public.telemetry (id) values (1) on conflict (id) do nothing;

-- ------------------------------------------------------------------
-- 2. ALERTS — APPEND-ONLY log (one insert per alert, never updated)
--    (existing columns id / mission_id / ts / kind / severity /
--     message / acked_by / acked_at are kept exactly as they are)
-- ------------------------------------------------------------------
alter table public.alerts add column if not exists alert_type text;    -- "BATTERY_LOW" | "SYSTEM_ERROR"
alter table public.alerts add column if not exists title      text;    -- e.g. "PAWS: BATTERY_LOW"
alter table public.alerts add column if not exists robot_id   text;    -- "PAWS_V1"
alter table public.alerts add column if not exists gait_state integer;
alter table public.alerts add column if not exists error_text text;
-- (severity + message already exist and are sent by the firmware)

-- Firmware does not send id / ts / kind: defaults so the existing
-- NOT NULL constraints pass on each append:
alter table public.alerts alter column id set default 'alrt_' || replace(gen_random_uuid()::text, '-', '');
alter table public.alerts alter column ts set default (extract(epoch from clock_timestamp()) * 1000)::bigint;

-- Map the firmware's alert_type onto the existing `kind` column that
-- the dashboard reads (BEFORE INSERT trigger; append-only, no UPDATE):
create or replace function public.firmware_alert_map_kind()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if new.kind is null then
    new.kind := coalesce(new.alert_type, 'system');
  end if;
  return new;
end;
$$;

drop trigger if exists firmware_alert_map_kind on public.alerts;
create trigger firmware_alert_map_kind
  before insert on public.alerts
  for each row execute function public.firmware_alert_map_kind();

-- ------------------------------------------------------------------
-- 3. ROW LEVEL SECURITY — the firmware authenticates with the ANON
--    key, so anon needs:
--      telemetry: INSERT + UPDATE  (upsert of the single live row)
--      alerts:    INSERT only      (append-only log)
--    Existing authenticated read/operator policies are untouched;
--    the dashboard reads server-side with the SERVICE ROLE key,
--    which bypasses RLS entirely.
-- ------------------------------------------------------------------
alter table public.telemetry enable row level security;
alter table public.alerts    enable row level security;

drop policy if exists "telemetry_anon_insert" on public.telemetry;
create policy "telemetry_anon_insert" on public.telemetry
  for insert to anon with check (true);

drop policy if exists "telemetry_anon_update" on public.telemetry;
create policy "telemetry_anon_update" on public.telemetry
  for update to anon using (true) with check (true);

drop policy if exists "alerts_anon_insert" on public.alerts;
create policy "alerts_anon_insert" on public.alerts
  for insert to anon with check (true);

-- ------------------------------------------------------------------
-- 4. REALTIME — let the live dashboard subscribe to both tables
--    (safe to re-run; duplicate_object is swallowed)
-- ------------------------------------------------------------------
do $$
begin
  begin alter publication supabase_realtime add table public.telemetry;
  exception when duplicate_object then null; end;
  begin alter publication supabase_realtime add table public.alerts;
  exception when duplicate_object then null; end;
end $$;

-- ------------------------------------------------------------------
-- 5. VERIFY — final columns and anon policies of both tables
-- ------------------------------------------------------------------
select table_name, column_name, data_type, is_nullable
from information_schema.columns
where table_schema = 'public'
  and table_name in ('telemetry', 'alerts')
order by table_name, ordinal_position;

select tablename, policyname, cmd, roles
from pg_policies
where schemaname = 'public'
  and tablename in ('telemetry', 'alerts')
order by tablename, policyname;

