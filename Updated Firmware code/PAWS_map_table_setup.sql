-- PAWS v5.0 estimated path map
-- Run this in Supabase SQL Editor before uploading the firmware.

create table if not exists public.paws_map_points (
  id bigint generated by default as identity primary key,
  robot_id text not null,
  session_id text not null,
  point_index integer not null,
  event_type text not null check (event_type in ('origin', 'pose', 'obstacle')),
  x_cm double precision not null,
  y_cm double precision not null,
  heading_deg real not null,
  sensor_bearing_deg real not null default 0,
  obstacle_range_cm real,
  obstacle_x_cm double precision,
  obstacle_y_cm double precision,
  created_at timestamptz not null default now(),
  unique (robot_id, session_id, point_index)
);

create index if not exists paws_map_points_session_order_idx
  on public.paws_map_points (robot_id, session_id, point_index);

alter table public.paws_map_points enable row level security;

grant select, insert on public.paws_map_points to anon;

drop policy if exists "PAWS demo can read map points" on public.paws_map_points;
create policy "PAWS demo can read map points"
  on public.paws_map_points for select to anon using (true);

drop policy if exists "PAWS demo can add map points" on public.paws_map_points;
create policy "PAWS demo can add map points"
  on public.paws_map_points for insert to anon with check (true);
